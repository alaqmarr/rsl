import Form from "next/form";
import {
  getAutoGeneratedRegistries,
  loadAllDocArticles,
  searchDocs,
} from "@rsl/docs";
import { SectionCard } from "@rsl/ui";
import { ActionLink, SubmitButton } from "@/components/ios-feedback";

export const dynamic = "force-dynamic";

export default async function DocsHomePage({
  searchParams,
}: {
  searchParams: Promise<{ q?: string }>;
}) {
  const sp = await searchParams;
  const query = (sp.q ?? "").trim();
  const articles = loadAllDocArticles();
  const hits = query ? searchDocs(query, "public") : [];
  const registries = getAutoGeneratedRegistries();

  const grouped = new Map<string, typeof articles>();
  for (const art of articles) {
    const bucket = grouped.get(art.section) ?? [];
    bucket.push(art);
    grouped.set(art.section, bucket);
  }

  return (
    <div className="space-y-8">
      <section className="rounded-2xl border border-zinc-200/90 bg-white p-6 shadow-2xs sm:p-8">
        <div className="max-w-2xl space-y-3">
          <span className="inline-flex items-center rounded-full bg-emerald-50 px-2.5 py-0.5 text-[11px] font-semibold tracking-wide text-emerald-800 uppercase ring-1 ring-emerald-200/80">
            Step-by-Step Setup Guides
          </span>
          <h1 className="text-2xl font-bold tracking-tight text-slate-900 sm:text-[26px]">
            How can we help you today?
          </h1>
          <p className="text-[13.5px] leading-relaxed text-zinc-600">
            Search clear guides for Tally Prime bill alerts, WhatsApp templates, cloud backups, GST
            invoices, and common error fixes.
          </p>
          <Form action="/" className="flex flex-col gap-2.5 pt-2 sm:flex-row">
            <input
              type="search"
              name="q"
              defaultValue={query}
              placeholder="Search Tally bills, WhatsApp templates, backups, GST invoice, API key..."
              className="rsl-input"
            />
            <SubmitButton className="rsl-btn-primary shrink-0" pendingText="Searching...">
              Search Guides
            </SubmitButton>
          </Form>
        </div>

        {query && (
          <div className="mt-6 border-t border-zinc-200/80 pt-5">
            <h2 className="text-[11px] font-bold tracking-wider text-zinc-500 uppercase">
              Search results for &ldquo;{query}&rdquo; ({hits.length})
            </h2>
            {hits.length === 0 ? (
              <p className="mt-2 text-[13px] text-zinc-500">
                No matching guide found. Try searching a simpler word like &ldquo;Tally&rdquo;,
                &ldquo;WhatsApp&rdquo;, &ldquo;backup&rdquo;, or &ldquo;wallet&rdquo;.
              </p>
            ) : (
              <div className="mt-3 grid gap-3 sm:grid-cols-2">
                {hits.map((h) => (
                  <ActionLink
                    key={`${h.kind}:${h.href}`}
                    href={h.href}
                    variant="card"
                    className="block rounded-xl border border-zinc-200/90 bg-zinc-50/60 p-4 transition hover:border-emerald-300 hover:bg-white"
                  >
                    <span className="text-[10px] font-bold tracking-wider text-emerald-700 uppercase">
                      {h.kind}
                    </span>
                    <p className="mt-1 text-[14px] font-semibold text-slate-900">{h.title}</p>
                    <p className="mt-1 text-xs leading-relaxed text-zinc-600">{h.summary}</p>
                  </ActionLink>
                ))}
              </div>
            )}
          </div>
        )}
      </section>

      <div className="space-y-7">
        {Array.from(grouped.entries()).map(([section, items]) => (
          <section key={section} className="space-y-3.5">
            <h2 className="text-[15px] font-semibold tracking-tight text-slate-900">{section}</h2>
            <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {items.map((item) => (
                <ActionLink
                  key={item.slug}
                  href={`/guides/${item.slug}`}
                  variant="card"
                  className="flex h-full flex-col justify-between rounded-2xl border border-zinc-200/90 bg-white p-5 shadow-2xs transition hover:border-emerald-300 hover:shadow-xs"
                >
                  <div>
                    <div className="flex items-center justify-between text-[11px] font-medium text-zinc-500 tabular-nums">
                      <span>{item.readingMinutes} min read</span>
                      <span>Updated {item.lastReviewed}</span>
                    </div>
                    <h3 className="mt-2.5 text-[15px] font-semibold tracking-tight text-slate-900">
                      {item.title}
                    </h3>
                    <p className="mt-1.5 text-[13px] leading-relaxed text-zinc-600">
                      {item.summary}
                    </p>
                  </div>
                  <span className="mt-4 inline-flex items-center text-xs font-semibold text-emerald-700">
                    Read guide →
                  </span>
                </ActionLink>
              ))}
            </div>
          </section>
        ))}
      </div>

      <SectionCard
        title="Team Roles & Permissions"
        subtitle="Choose the right access level when inviting staff members to your business account"
        action={
          <div className="flex flex-wrap gap-2">
            <ActionLink href="/api-reference" className="rsl-btn-secondary">
              Developer API ({registries.apiEndpoints.length} routes)
            </ActionLink>
            <ActionLink href="/errors" className="rsl-btn-secondary">
              Common Errors ({registries.errors.length})
            </ActionLink>
          </div>
        }
        noPadding
      >
        <div className="overflow-x-auto">
          <table className="w-full text-left text-[13px]">
            <thead className="border-b border-zinc-200/80 bg-zinc-50/70 text-[11px] font-semibold tracking-wide text-zinc-500 uppercase">
              <tr>
                <th className="px-5 py-3 sm:px-6">Role</th>
                <th className="px-4 py-3">Who It Is For</th>
                <th className="px-5 py-3 sm:px-6">Access Included</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-zinc-100 bg-white">
              {registries.roles.map((r) => (
                <tr key={r.slug} className="hover:bg-zinc-50/60">
                  <td className="px-5 py-3 font-semibold text-slate-900 sm:px-6">{r.name}</td>
                  <td className="px-4 py-3 text-zinc-600">{r.description}</td>
                  <td className="px-5 py-3 font-mono text-xs font-semibold text-emerald-700 tabular-nums sm:px-6">
                    {r.permissions.length} permissions
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </SectionCard>
    </div>
  );
}
